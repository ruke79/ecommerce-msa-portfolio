package com.project.catalog_service.model;

/**
 * 기획전의 상태.
 *
 * <p><b>왜 {@code published} 불리언 하나로 두지 않았나.</b> 배너·공지는 그렇게 해도 됐다 —
 * "지금 보이는가"만 알면 되기 때문이다. 기획전은 다르다. 할인이 걸려 있어서 <b>언제
 * 시작했고 언제 끝났는지</b>가 사후에도 의미를 갖는다. 끝난 기획전과 아직 시작하지 않은
 * 기획전을 같은 "published=false" 로 묶으면, 관리자 목록에서 둘을 구분할 수 없고 "왜 안
 * 보이지?"를 매번 시작·종료 시각을 읽어 추론해야 한다.
 *
 * <p>상태는 스케줄러가 시각에 맞춰 넘긴다({@code EventScheduler}). 사람이 자정에 맞춰
 * 버튼을 누르는 방식은 반드시 놓친다.
 *
 * <p>[JA] 企画展の状態。
 * なぜ published ブール値一つにしなかったのか。バナー・お知らせはそれでよかった — 「今見えるか」さえ分かればよいからだ。企画展は違う。
 * 割引がかかっているので、いつ始まりいつ終わったかが事後にも意味を持つ。終わった企画展とまだ始まっていない企画展を同じ「published=false」で括ると、
 * 管理者一覧で両者を区別できず、「なぜ見えない?」を毎回開始・終了時刻を読んで推測しなければならない。
 * 状態はスケジューラが時刻に合わせて進める(EventScheduler)。人が深夜 0 時に合わせてボタンを押す方式は必ず取りこぼす。
 */
public enum EventStatus {

    /**
     * 작성 중. 아무 데도 보이지 않고 할인도 걸리지 않는다.
     *
     * <p>시작 시각이 이미 지났어도 DRAFT 면 시작되지 않는다 — 준비가 안 된 기획전이
     * 저장하자마자 나가는 것을 막는다.
     *
     * <p>[JA] 作成中。どこにも見えず割引もかからない。
     * 開始時刻をすでに過ぎていても DRAFT なら開始されない — 準備ができていない企画展が保存した途端に出るのを防ぐ。
     */
    DRAFT,

    /** 확정됐고 시작 시각을 기다린다. 스케줄러가 {@link #ACTIVE} 로 넘긴다. */
    // [JA] 確定済みで開始時刻を待っている。スケジューラが ACTIVE へ進める。
    SCHEDULED,

    /** 진행 중. 이 상태일 때만 할인이 상품 가격에 합성된다. */
    // [JA] 進行中。この状態のときだけ割引が商品価格に合成される。
    ACTIVE,

    /** 끝났다. 할인은 즉시 사라지고 목록에는 기록으로 남는다. */
    // [JA] 終了した。割引は即座に消え、一覧には記録として残る。
    ENDED;

    /** 지금 할인이 적용되는 상태인가. */
    // [JA] 今、割引が適用される状態か。
    public boolean isActive() {
        return this == ACTIVE;
    }

    /** 사용자에게 보이는 상태인가(진행 중이거나 끝난 것 — 초안과 예약분은 감춘다). */
    // [JA] ユーザーに見える状態か(進行中または終了したもの — 下書きと予約分は隠す)。
    public boolean isPublic() {
        return this == ACTIVE;
    }
}
