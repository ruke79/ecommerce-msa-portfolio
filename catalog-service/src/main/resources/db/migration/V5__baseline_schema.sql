-- catalog-service 스키마 베이스라인 — Flyway 가 스키마를 소유한다 (docs/20).
--
-- ⚠️ 손으로 쓰지 말 것. Hibernate 가 엔티티에서 생성한 DDL 을 기계 변환한 것이다:
--     ./gradlew -PexportSchema -PwithContainers :catalog-service:test --tests '*ApplicationTests*'
--     ./ops/tools/hbm2flyway.py build/schema/catalog-service.sql -o <이 파일>
--
-- 왜 베이스라인이 필요한가: 예전에는 `ddl-auto: update` 가 스키마를 만들었다. 그래서
--   · 스키마 변경이 이력에 남지 않고 (무엇이 언제 왜 바뀌었는지 아무도 모른다)
--   · 운영 DB 에 예고 없는 DDL 이 나가며
--   · 제약을 **지우지는 않아** 잘못된 제약이 영원히 남는다 (V4 가 그 뒤처리였다)
-- 이제 Flyway 가 소유하고 Hibernate 는 `validate` 로 검증만 한다.
--
-- 모든 문장이 멱등이다. 빈 DB 에서는 전부 만들고, `ddl-auto` 가 이미 만들어 둔 DB 에서는
-- 전부 건너뛴다. 그래서 기존 환경도 이 마이그레이션을 그대로 통과한다.
--
-- 파일 끝의 `add column if not exists` 묶음은 기존 DB 가 엔티티보다 **뒤처진** 경우를 메운다.
-- "그건 ddl-auto 랑 뭐가 다르냐"에 대한 답: ddl-auto 는 매 기동마다 그때의 코드에서 DDL 을
-- 새로 유추해 **검토 없이** 실행한다. 이건 커밋된 파일에 적힌 고정된 문장 목록이고, 리뷰를
-- 거치며, Flyway 가 기록하므로 **딱 한 번만** 실행된다. 뒤에 스키마를 또 바꾸려면 새 마이그
-- 레이션을 써야 한다. 컬럼은 반드시 널 허용으로 추가한다 — 기존 행이 있는 테이블에 기본값
-- 없는 NOT NULL 은 붙지 않기 때문이고, validate 는 널 여부가 아니라 존재와 타입만 본다.
--
-- 스키마 1 · 시퀀스 0 · 테이블 10 · 인덱스 9 · 제약 9

CREATE SCHEMA IF NOT EXISTS product;

CREATE TABLE IF NOT EXISTS product.category (
    category_id bigint generated by default as identity,
    createdAt timestamp(6),
    updatedAt timestamp(6),
    version bigint,
    category_name varchar(255),
    createdBy varchar(255),
    slug varchar(255),
    updatedBy varchar(255),
    primary key (category_id)
);

CREATE TABLE IF NOT EXISTS product.processed_event (
    processed_at timestamp(6) not null,
    event_id varchar(64) not null,
    primary key (event_id)
);

CREATE TABLE IF NOT EXISTS product.product (
    rating float4 not null,
    shipping numeric(38,2),
    category_id bigint not null,
    createdAt timestamp(6),
    product_id bigint generated by default as identity,
    updatedAt timestamp(6),
    version bigint,
    description varchar(1000),
    brand varchar(255),
    createdBy varchar(255),
    name varchar(255),
    refundPolicy varchar(255),
    slug varchar(255),
    updatedBy varchar(255),
    primary key (product_id)
);

CREATE TABLE IF NOT EXISTS product.product_color (
    color_id bigint generated by default as identity,
    createdAt timestamp(6),
    updatedAt timestamp(6),
    version bigint,
    color varchar(255),
    colorImage varchar(255),
    createdBy varchar(255),
    updatedBy varchar(255),
    primary key (color_id)
);

CREATE TABLE IF NOT EXISTS product.product_details (
    createdAt timestamp(6),
    pdetail_id bigint generated by default as identity,
    product_id bigint not null,
    updatedAt timestamp(6),
    version bigint,
    createdBy varchar(255),
    name varchar(255),
    updatedBy varchar(255),
    value varchar(255),
    primary key (pdetail_id)
);

CREATE TABLE IF NOT EXISTS product.product_qa (
    createdAt timestamp(6),
    product_id bigint not null,
    qa_id bigint generated by default as identity,
    updatedAt timestamp(6),
    version bigint,
    answer varchar(255),
    createdBy varchar(255),
    question varchar(255),
    updatedBy varchar(255),
    primary key (qa_id)
);

CREATE TABLE IF NOT EXISTS product.product_size (
    price numeric(38,2),
    quantity integer not null,
    createdAt timestamp(6),
    size_id bigint generated by default as identity,
    skuproduct_id bigint,
    updatedAt timestamp(6),
    version bigint,
    createdBy varchar(255),
    size varchar(255),
    updatedBy varchar(255),
    primary key (size_id)
);

CREATE TABLE IF NOT EXISTS product.product_sku (
    discount integer not null,
    sold integer not null,
    color_id bigint,
    createdAt timestamp(6),
    product_id bigint not null,
    skuproduct_id bigint generated by default as identity,
    updatedAt timestamp(6),
    version bigint,
    createdBy varchar(255),
    sku varchar(255),
    updatedBy varchar(255),
    images varchar(256) array,
    primary key (skuproduct_id)
);

CREATE TABLE IF NOT EXISTS product.product_subcategory (
    proc_subcategory_id bigint generated by default as identity,
    product_id bigint,
    subcategory_id bigint,
    version bigint,
    primary key (proc_subcategory_id)
);

CREATE TABLE IF NOT EXISTS product.subcategory (
    category_id bigint not null,
    createdAt timestamp(6),
    subcategory_id bigint generated by default as identity,
    updatedAt timestamp(6),
    version bigint,
    createdBy varchar(255),
    slug varchar(255),
    subcategory_name varchar(255),
    updatedBy varchar(255),
    primary key (subcategory_id)
);

CREATE INDEX IF NOT EXISTS idx_category on product.category (category_name, slug);

CREATE INDEX IF NOT EXISTS idx_product on product.product (name, brand, slug, category_id);

CREATE INDEX IF NOT EXISTS idx_product_color on product.product_color (color);

CREATE INDEX IF NOT EXISTS idx_product_details on product.product_details (name);

CREATE INDEX IF NOT EXISTS idx_product_size on product.product_size (size);

CREATE INDEX IF NOT EXISTS idx_product_sku on product.product_sku (sku, sold);

CREATE INDEX IF NOT EXISTS idx_product_sku_color_id on product.product_sku (color_id);

CREATE INDEX IF NOT EXISTS idx_product_subcategory on product.product_subcategory (subcategory_id, product_id);

CREATE INDEX IF NOT EXISTS idx_subcategory on product.subcategory (subcategory_name, slug);

