-- Spring Batch 메타데이터 스키마 (docs/16 §7 결정 사항).
--
-- 결정: **배치 메타데이터는 기본 데이터소스(productdb)의 meta 스키마가 소유한다.**
--
-- 배경: 설정은 `spring.datasource-meta`(metadb) + `table-prefix: meta.BATCH_` 로 되어 있었지만,
-- Spring Batch 의 JobRepository 는 @Primary 데이터소스를 쓰므로 실제로는 productdb 를 보고 있었다.
-- 게다가 meta 스키마를 만드는 곳이 아무 데도 없어(주석에 "미리 실행" 이라고만 적혀 있었다)
-- **신규 환경에서는 모든 배치 잡이 실패**했다:
--
--   ERROR: relation "meta.batch_job_instance" does not exist
--
-- 그 결과 ES 색인 잡도, CSV 상품 임포트도 돌지 않았다 — ES 검색 전환(ops/03)이 막혀 있던 원인 중 하나다.
--
-- 왜 metadb 가 아니라 productdb 인가:
--   - 실제 동작과 설정을 일치시키는 방향이 변경 폭이 가장 작고 안전하다.
--   - Flyway 는 기본 데이터소스를 대상으로 돌기 때문에, 이 마이그레이션 하나로 스키마 생성이 자동화된다.
--     (metadb 로 옮기려면 두 번째 Flyway 대상을 도입해야 하고, 배치 메타를 굳이 별도 DB 에 둘
--      운영상의 이득도 없다 — 배치 메타는 업무 데이터와 함께 백업/복구되는 편이 낫다.)
--   - 사용하지 않게 된 `spring.datasource-meta` 는 혼동을 막기 위해 설정에 주석으로 표시해 둔다.
--
-- 스크립트는 Spring Batch 5.2.1 의 schema-postgresql.sql 을 meta 스키마로 옮기고
-- IF NOT EXISTS 를 붙여 **재실행 안전**하게 만든 것이다.
