-- 1) 시드 상품: 새 매핑에 없는 연결은 지운다(무작위였던 옛 연결 — 같은 카테고리 안의 것도).
DELETE FROM product.product_subcategory ps
USING product.product p, product.subcategory s
WHERE ps.product_id = p.product_id
  AND ps.subcategory_id = s.subcategory_id
  AND p.slug IN (SELECT slug FROM seed_product)
  AND NOT EXISTS (
      SELECT 1 FROM seed_link m
      WHERE m.slug = p.slug AND lower(m.subcategory_name) = lower(s.subcategory_name)
  );

-- 2) 모든 상품: 상품의 카테고리에 속하지 않는 하위 카테고리 연결은 정의상 틀렸다 — 지운다
--    (관리자가 등록한 상품도 같은 규칙. ProductService 가 이제 등록할 때 막는다).
DELETE FROM product.product_subcategory ps
USING product.product p, product.subcategory s
WHERE ps.product_id = p.product_id
  AND ps.subcategory_id = s.subcategory_id
  AND s.category_id <> p.category_id;

-- 3) 시드 상품을 새 매핑대로 잇는다(없을 때만). 맞는 하위 카테고리가 없는 상품(TV · 스피커 · 올리브유 · 러그 …)은 잇지 않는다.
INSERT INTO product.product_subcategory (product_id, subcategory_id, version)
SELECT p.product_id, s.subcategory_id, 0
FROM seed_link m
JOIN product.product p ON p.slug = m.slug
JOIN product.subcategory s ON lower(s.subcategory_name) = lower(m.subcategory_name) AND s.category_id = p.category_id
WHERE NOT EXISTS (
    SELECT 1 FROM product.product_subcategory x
    WHERE x.product_id = p.product_id AND x.subcategory_id = s.subcategory_id
);
