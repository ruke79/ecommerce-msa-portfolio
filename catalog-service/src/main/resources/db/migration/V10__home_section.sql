-- 홈 화면 섹션 — 첫 화면의 구성을 데이터로 옮긴다.
--
-- **무엇이 문제였나.** 홈에 보이는 카테고리 다섯 개가 프론트엔드 코드에 박혀 있었다
-- (CategoryProducts.jsx 와 Home.jsx 에 각각 다섯 줄씩, 같은 목록이 두 곳에). 어드민에서
-- 카테고리를 새로 만들어도 홈에는 나오지 않고, 순서를 바꾸려면 재배포해야 했다.
-- 배너가 번들에 박혀 있던 것과 같은 문제다.
--
-- **왜 "카테고리 전체를 그리면" 안 되나.** 카테고리 목록을 API 로 받아 전부 렌더하면
-- 하드코딩은 사라지지만 운영이 불가능해진다 — 카테고리가 열 개가 되는 순간 홈에 섹션이
-- 열 개 쏟아지고, 무엇을 위에 둘지도 정할 수 없다. 실무의 홈은 전체 나열이 아니라
-- **큐레이션**이다. 그래서 "어떤 섹션을, 어떤 순서로, 언제부터 언제까지"를 행으로 둔다.
--
-- **기간을 두는 이유는 배너와 같다.** 기획전 섹션은 주말에만 띄우는 식으로 쓰인다.
-- 사람이 시각에 맞춰 체크박스를 켜고 끄면 반드시 놓친다.
--
-- **카테고리를 이름으로 가리키는 이유.** 상품 조회 API 가 이름을 받는다
-- (ProductService.getProductsByCategory). 외래키를 걸면 스키마가 달라(content ↔ product)
-- 결합이 생기고, 카테고리가 지워질 때 섹션까지 연쇄 삭제된다. 이름 참조는 대상이 없어지면
-- **그 섹션만 조용히 빠지고** 나머지 홈은 그대로 뜬다 — 첫 화면에서는 그쪽이 맞다.
-- 대신 어드민 화면이 "이 섹션이 가리키는 카테고리가 없다"를 표시한다.

CREATE TABLE IF NOT EXISTS content.home_section (
    section_id       bigint       GENERATED BY DEFAULT AS IDENTITY,
    -- 화면에 보이는 제목. 카테고리 이름과 다를 수 있다("가전" 카테고리를 "새로 나온 가전"으로).
    title            varchar(200) NOT NULL,
    -- CATEGORY | SUBCATEGORY. 무엇을 기준으로 상품을 고르는가.
    kind             varchar(20)  NOT NULL,
    category_name    varchar(100) NOT NULL,
    -- kind=SUBCATEGORY 일 때만 쓴다.
    subcategory_name varchar(100),
    -- GRID(상단 격자 카드) | SWIPER(가로 스와이퍼). 화면에서의 생김새.
    layout           varchar(20)  NOT NULL DEFAULT 'SWIPER',
    -- 이 섹션이 보여 줄 상품 수.
    item_limit       int          NOT NULL DEFAULT 10,
    sort_order       int          NOT NULL DEFAULT 0,
    published        boolean      NOT NULL DEFAULT false,
    starts_at        timestamp(6),
    ends_at          timestamp(6),
    created_at       timestamp(6),
    updated_at       timestamp(6),
    PRIMARY KEY (section_id)
);

-- 공개 조회는 언제나 "published 이고 기간 안에 있는 것을 sort_order 순으로"다.
CREATE INDEX IF NOT EXISTS idx_home_section_visible
    ON content.home_section (published, sort_order);

