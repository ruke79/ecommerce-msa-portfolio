-- 이벤트 / 기획전 (docs/44 §3).
--
-- ROLLBACK-SAFE: 새 테이블 둘만 만든다. 기존 데이터를 건드리지 않는다.
--
-- ── 왜 새 개념이 필요한가 ────────────────────────────────────────────────
--
-- "기간 한정 세일"에 해당하는 것이 코드에 없었다. 가장 가까운 것들이 각각 모자랐다:
--
--   · content.home_section  홈에 섹션을 배치할 뿐 — 기간도 할인율도 없다
--   · content.banner        이미지와 링크일 뿐
--   · coupon                사용자가 쿠폰을 가져야 한다. 상품 가격 자체는 그대로다
--   · product_sku.discount  상품마다 손으로 고쳐야 하고, 기간이 없다
--
-- ── 🔴 할인율을 product_sku.discount 에 덮어쓰지 않는 이유 ─────────────────
--
-- 가장 쉬운 구현은 이벤트가 시작될 때 대상 상품의 discount 를 이벤트 할인율로 바꾸고,
-- 끝날 때 원래 값으로 되돌리는 것이다. **그러면 안 된다.**
--
-- 되돌릴 원래 값을 어딘가 적어 둬야 하는데, 이벤트가 진행되는 동안 관리자가 그 상품을
-- 수정하면(정가 할인을 10%에서 15%로 올린다든지) 이벤트 종료 시 복원이 그 수정을 덮는다.
-- 관리자는 자기가 방금 한 수정이 왜 사라졌는지 알 수 없다. 이벤트 두 개가 같은 상품을
-- 겹쳐 잡으면 더 나빠진다 — 먼저 끝나는 쪽이 복원하면서 다른 이벤트의 할인까지 지운다.
--
-- 그래서 할인율은 **이 테이블에만** 있고, 상품을 조회할 때 합성한다(EventPricing).
-- product_sku.discount 는 언제나 "이벤트와 무관한 상시 할인"이라는 하나의 뜻만 갖는다.

CREATE TABLE IF NOT EXISTS content.event (
    event_id         bigint        GENERATED BY DEFAULT AS IDENTITY,
    title            varchar(200)  NOT NULL,
    -- URL 에 쓰는 이름. 숫자 id 를 노출하면 링크가 "무엇에 대한 것인지" 말해 주지 않고,
    -- 진행 중인 기획전 수가 그대로 드러난다.
    slug             varchar(200)  NOT NULL,
    description      varchar(2000),
    banner_image_url varchar(1000),
    -- 기본은 /event/<slug> 다. 다른 곳으로 보내고 싶을 때만 채운다.
    link_url         varchar(1000),
    -- DRAFT · SCHEDULED · ACTIVE · ENDED (EventStatus). 문자열로 두는 이유는
    -- 배너·공지와 같다 — DB 를 직접 들여다보는 사람이 숫자를 해석하지 않아도 된다.
    status           varchar(16)   NOT NULL DEFAULT 'DRAFT',
    starts_at        timestamp(6),
    ends_at          timestamp(6),
    created_at       timestamp(6),
    updated_at       timestamp(6),
    PRIMARY KEY (event_id),
    -- slug 가 겹치면 /event/<slug> 가 어느 쪽인지 정해지지 않는다. 애플리케이션이 만들 때
    -- 겹침을 피하지만, 두 관리자가 동시에 저장하면 그 검사를 둘 다 통과한다.
    CONSTRAINT uq_event_slug UNIQUE (slug)
);

-- 스케줄러가 "시작할 때가 된 것"과 "끝낼 때가 된 것"을 1분마다 찾는다.
CREATE INDEX IF NOT EXISTS idx_event_status_starts
    ON content.event (status, starts_at);

CREATE TABLE IF NOT EXISTS content.event_product (
    event_id      bigint NOT NULL,
    product_id    bigint NOT NULL,
    -- 퍼센트다(0~100). product_sku.discount 와 같은 단위 — 다른 단위를 섞으면
    -- 합성하는 쪽에서 반드시 틀린다.
    discount_rate int    NOT NULL,
    -- 복합 키라 한 이벤트가 같은 상품을 두 번 담을 수 없다. 담기면 어느 할인율이
    -- 적용되는지가 조회 순서에 따라 달라진다.
    PRIMARY KEY (event_id, product_id)
);

-- 상품 조회 때 "이 상품에 걸린 진행 중인 이벤트"를 찾는다. PostgreSQL 은 FK 컬럼에
-- 인덱스를 자동으로 만들지 않고, 여기는 FK 조차 없다(아래 참조).
CREATE INDEX IF NOT EXISTS idx_event_product_product
    ON content.event_product (product_id);

-- FK 를 걸지 않는다.
--
-- product_id 는 **다른 스키마**(product.product)를 가리킨다. 이 두 테이블은 content 스키마에
-- 있고, content 는 언젠가 별도 서비스로 떼어낼 수 있도록 일부러 나눠 둔 경계다(V9 주석).
-- 스키마를 가로지르는 FK 를 걸면 그 경계가 DB 제약으로 굳어져 분리가 불가능해진다.
--
-- 대신 없는 상품을 가리키는 행은 조회에서 그냥 빠진다 — 할인이 적용될 상품이 없을 뿐이고,
-- 가격이 틀리지는 않는다. 관리자 화면은 저장 시점에 상품 존재를 확인한다.
