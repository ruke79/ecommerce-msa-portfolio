-- 배너와 공지.
--
-- **왜 이 두 개가 먼저인가.** 홈 화면의 배너 5장은 프론트엔드 번들에 박혀 있었다
-- (CarouselContainer.jsx 의 `import slider1 from "assets/images/slider-1.jpg"`). 배너 하나
-- 바꾸려면 재빌드·재배포였다. 공지사항은 아예 없어서 서비스 점검이나 정책 변경을 알릴
-- 방법이 없었다. 재배포 없이는 못 바꾸는 것이 정확히 이 둘이다.
--
-- **왜 product 가 아니라 별도 스키마인가.** 이 테이블들은 카탈로그 도메인이 아니다 —
-- 주문·재고와 트랜잭션을 공유하지 않고, 검색 색인에도 들어가지 않는다. 같은 DB 에 두되
-- 스키마를 나눠 두면 "product.banner" 같은 잘못된 소속을 이름으로 주장하지 않게 되고,
-- 나중에 별도 서비스로 다시 떼어낼 때 무엇을 가져가야 하는지가 스키마 경계로 드러난다.
--
-- **노출 판정을 published 하나로 하지 않는 이유.** 기획전 배너는 "금요일 0시부터 일요일
-- 자정까지"처럼 기간이 정해져 있다. 그걸 사람이 시각에 맞춰 체크박스를 켜고 끄는 방식으로
-- 운영하면 반드시 놓친다. starts_at / ends_at 을 두고 서버가 판정한다. 둘 다 NULL 이면
-- "기간 제한 없음"이라 published 만 보면 된다 — 상시 배너는 그대로 단순하게 쓴다.
--
-- **본문을 text 로 둔 이유.** 공지 본문은 길이를 예측할 수 없다. varchar(n) 으로 잡으면
-- 언젠가 n 을 늘리는 마이그레이션을 하게 되고, 그동안 운영자는 글자 수를 세야 한다.
-- Postgres 에서 text 와 varchar 는 저장 방식이 같아 성능 차이가 없다.

CREATE SCHEMA IF NOT EXISTS content;

CREATE TABLE IF NOT EXISTS content.banner (
    banner_id  bigint        GENERATED BY DEFAULT AS IDENTITY,
    title      varchar(200)  NOT NULL,
    image_url  varchar(1000) NOT NULL,
    -- 클릭했을 때 갈 곳. 비워 두면 클릭되지 않는 배너다(공지성 이미지).
    link_url   varchar(1000),
    sort_order int           NOT NULL DEFAULT 0,
    published  boolean       NOT NULL DEFAULT false,
    starts_at  timestamp(6),
    ends_at    timestamp(6),
    created_at timestamp(6),
    updated_at timestamp(6),
    PRIMARY KEY (banner_id)
);

-- 공개 조회는 언제나 "published 이고 기간 안에 있는 것을 sort_order 순으로"다.
CREATE INDEX IF NOT EXISTS idx_banner_visible
    ON content.banner (published, sort_order);

CREATE TABLE IF NOT EXISTS content.notice (
    notice_id    bigint       GENERATED BY DEFAULT AS IDENTITY,
    title        varchar(200) NOT NULL,
    body         text         NOT NULL,
    -- 상단 고정. 점검 공지처럼 최신이 아니어도 맨 위에 있어야 하는 글이 있다.
    pinned       boolean      NOT NULL DEFAULT false,
    published    boolean      NOT NULL DEFAULT false,
    -- 공개한 시각. 작성 시각(created_at)과 다르다 — 미리 써 두고 나중에 공개할 수 있다.
    published_at timestamp(6),
    created_at   timestamp(6),
    updated_at   timestamp(6),
    PRIMARY KEY (notice_id)
);

CREATE INDEX IF NOT EXISTS idx_notice_published
    ON content.notice (published, pinned DESC, published_at DESC);
