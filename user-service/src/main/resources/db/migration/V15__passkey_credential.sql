-- 패스키(WebAuthn) 자격증명 — 비밀번호 없이, 피싱에 넘어가지 않는 로그인(docs/68 §20).
-- [JA] パスキー(WebAuthn)の資格情報 — パスワードなしで、フィッシングに負けないログイン。
--
-- ROLLBACK-SAFE: 새 테이블 하나. 기존 데이터를 건드리지 않는다. 옛 이미지는 이 테이블을 모른다(쓰지 않을 뿐이다).
--
-- ── 무엇을 저장하나 ────────────────────────────────────────────────────
--
-- 공개 키뿐이다. 비밀 키는 사용자의 기기(휴대폰 · 노트북 · 보안 키)를 떠나지 않는다 — 이 표가 통째로 새어도
-- 로그인에 쓸 수 있는 값은 없다. 비밀번호 해시처럼 오프라인으로 깰 대상조차 없다.
--
--   attested_credential_data — 인증기가 등록 때 준 그대로(AAGUID + 자격증명 id + COSE 공개 키). 검증 라이브러리가 그대로 다시 읽는다.
--   sign_count               — 인증기가 서명할 때마다 올리는 수. 줄어들면 복제된 키다(라이브러리가 거절한다). 동기화 패스키는 늘 0 이다.
--   user_handle              — 브라우저가 로그인 때 돌려주는 "이 계정" 표시. 이메일 · userId 대신 난수다(기기에 남는 값이라 개인정보를 넣지 않는다).
CREATE TABLE IF NOT EXISTS users.passkey_credential (
    passkey_id                bigint        GENERATED BY DEFAULT AS IDENTITY,
    user_id                   bigint        NOT NULL,
    -- base64url(자격증명 id). 로그인 때 이것으로 찾는다 — 전역에서 하나.
    credential_id             varchar(1400) NOT NULL,
    user_handle               varchar(64)   NOT NULL,
    attested_credential_data  bytea         NOT NULL,
    sign_count                bigint        NOT NULL DEFAULT 0,
    uv_initialized            boolean       NOT NULL DEFAULT true,
    backup_eligible           boolean,
    backup_state              boolean,
    -- 쉼표로 이은 전송 방식(internal, hybrid, usb ...) — 로그인 화면의 힌트일 뿐 판정에 쓰지 않는다.
    transports                varchar(120),
    -- 사용자가 붙인 이름("내 아이폰"). 표시용.
    name                      varchar(60)   NOT NULL,
    created_at                timestamp     NOT NULL,
    last_used_at              timestamp,
    CONSTRAINT pk_passkey_credential PRIMARY KEY (passkey_id),
    CONSTRAINT uk_passkey_credential_id UNIQUE (credential_id)
);

CREATE INDEX IF NOT EXISTS idx_passkey_credential_user ON users.passkey_credential (user_id);
