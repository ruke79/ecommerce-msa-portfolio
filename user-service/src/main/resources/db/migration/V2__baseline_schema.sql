-- user-service 스키마 베이스라인 — Flyway 가 스키마를 소유한다 (docs/20).
--
-- ⚠️ 손으로 쓰지 말 것. Hibernate 가 엔티티에서 생성한 DDL 을 기계 변환한 것이다:
--     ./gradlew -PexportSchema -PwithContainers :user-service:test --tests '*ApplicationTests*'
--     ./ops/tools/hbm2flyway.py build/schema/user-service.sql -o <이 파일>
--
-- 왜 베이스라인이 필요한가: 예전에는 `ddl-auto: update` 가 스키마를 만들었다. 그래서
--   · 스키마 변경이 이력에 남지 않고 (무엇이 언제 왜 바뀌었는지 아무도 모른다)
--   · 운영 DB 에 예고 없는 DDL 이 나가며
--   · 제약을 **지우지는 않아** 잘못된 제약이 영원히 남는다 (V4 가 그 뒤처리였다)
-- 이제 Flyway 가 소유하고 Hibernate 는 `validate` 로 검증만 한다.
--
-- 모든 문장이 멱등이다. 빈 DB 에서는 전부 만들고, `ddl-auto` 가 이미 만들어 둔 DB 에서는
-- 전부 건너뛴다. 그래서 기존 환경도 이 마이그레이션을 그대로 통과한다.
--
-- 파일 끝의 `add column if not exists` 묶음은 기존 DB 가 엔티티보다 **뒤처진** 경우를 메운다.
-- "그건 ddl-auto 랑 뭐가 다르냐"에 대한 답: ddl-auto 는 매 기동마다 그때의 코드에서 DDL 을
-- 새로 유추해 **검토 없이** 실행한다. 이건 커밋된 파일에 적힌 고정된 문장 목록이고, 리뷰를
-- 거치며, Flyway 가 기록하므로 **딱 한 번만** 실행된다. 뒤에 스키마를 또 바꾸려면 새 마이그
-- 레이션을 써야 한다. 컬럼은 반드시 널 허용으로 추가한다 — 기존 행이 있는 테이블에 기본값
-- 없는 NOT NULL 은 붙지 않기 때문이고, validate 는 널 여부가 아니라 존재와 타입만 본다.
--
-- 스키마 1 · 시퀀스 0 · 테이블 10 · 인덱스 10 · 제약 7

CREATE SCHEMA IF NOT EXISTS users;

CREATE TABLE IF NOT EXISTS users.notification (
    is_read boolean,
    created_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6),
    version bigint,
    created_by varchar(255),
    email varchar(255),
    message varchar(255),
    session_id varchar(255),
    updated_by varchar(255),
    primary key (id)
);

CREATE TABLE IF NOT EXISTS users.outbox_event (
    created_at timestamp(6) not null,
    aggregate_id varchar(255) not null,
    aggregate_type varchar(255) not null,
    event_type varchar(255) not null,
    id varchar(255) not null,
    payload jsonb not null,
    primary key (id)
);

CREATE TABLE IF NOT EXISTS users.password_reset_token (
    used boolean not null,
    expiry_date timestamp(6) with time zone not null,
    id bigint not null,
    user_id bigint not null,
    version bigint,
    token varchar(255) not null unique,
    primary key (id)
);

CREATE TABLE IF NOT EXISTS users.review (
    rating float4 not null,
    created_at timestamp(6),
    product_id bigint,
    review_id bigint not null,
    rstyle_id bigint not null unique,
    updated_at timestamp(6),
    user_id bigint not null,
    version bigint,
    created_by varchar(255),
    fit varchar(255),
    review varchar(255),
    size varchar(255),
    updated_by varchar(255),
    images varchar(255) array,
    primary key (review_id)
);

CREATE TABLE IF NOT EXISTS users.review_style (
    created_at timestamp(6),
    rstyle_id bigint not null,
    updated_at timestamp(6),
    version bigint,
    color varchar(255),
    created_by varchar(255),
    image varchar(255),
    updated_by varchar(255),
    primary key (rstyle_id)
);

CREATE TABLE IF NOT EXISTS users.roles (
    role_id bigint not null,
    role_name varchar(20) check (role_name in ('ROLE_USER','ROLE_ADMIN')),
    primary key (role_id)
);

CREATE TABLE IF NOT EXISTS users.shipping_address (
    active boolean not null,
    created_at timestamp(6),
    shipping_address_id bigint not null,
    updated_at timestamp(6),
    user_id bigint not null,
    version bigint,
    address1 varchar(255) not null,
    address2 varchar(255),
    city varchar(255) not null,
    country varchar(255),
    created_by varchar(255),
    firstname varchar(255),
    lastname varchar(255),
    phone_number varchar(255),
    state varchar(255) not null,
    updated_by varchar(255),
    zip_code varchar(255) not null,
    primary key (shipping_address_id)
);

CREATE TABLE IF NOT EXISTS users.users (
    account_expiry_date date,
    account_non_expired boolean not null,
    account_non_locked boolean not null,
    credentials_expiry_date date,
    credentials_non_expired boolean not null,
    email_verified boolean not null,
    enabled boolean not null,
    is_two_factor_enabled boolean not null,
    created_at timestamp(6),
    role_id bigint,
    updated_at timestamp(6),
    user_id bigint not null,
    version bigint,
    name varchar(20),
    username varchar(20) not null,
    email varchar(50) not null,
    password varchar(120),
    created_by varchar(255),
    default_payment_method varchar(255),
    image varchar(255),
    sign_up_method varchar(255),
    two_factor_secret varchar(255),
    updated_by varchar(255),
    primary key (user_id),
    unique (username),
    unique (email)
);

CREATE TABLE IF NOT EXISTS users.verfication_token (
    expiry_date timestamp(6),
    id bigint not null,
    user_id bigint not null unique,
    token varchar(255),
    primary key (id)
);

CREATE TABLE IF NOT EXISTS users.wishlist (
    created_at timestamp(6),
    product_id bigint,
    updated_at timestamp(6),
    user_id bigint not null,
    version bigint,
    wish_item_id bigint not null,
    created_by varchar(255),
    style varchar(255),
    updated_by varchar(255),
    primary key (wish_item_id)
);

CREATE INDEX IF NOT EXISTS idx_notification on users.notification (email, session_id);

CREATE INDEX IF NOT EXISTS idx_outbox_event on users.outbox_event (aggregate_id, aggregate_type, event_type);

CREATE INDEX IF NOT EXISTS idx_password_reset_token on users.password_reset_token (token, user_id);

CREATE INDEX IF NOT EXISTS idx_review on users.review (rating, review, size, fit);

CREATE INDEX IF NOT EXISTS idx_review_style on users.review_style (color, image);

CREATE INDEX IF NOT EXISTS idx_role_name on users.roles (role_name);

CREATE INDEX IF NOT EXISTS idx_shipping_address on users.shipping_address (firstname, lastname, address1, city, state, zip_code);

CREATE INDEX IF NOT EXISTS idx_user on users.users (username, email);

CREATE INDEX IF NOT EXISTS idx_verification_token on users.verfication_token (token, user_id);

CREATE INDEX IF NOT EXISTS idx_wishItem on users.wishlist (style, user_id, product_id);

