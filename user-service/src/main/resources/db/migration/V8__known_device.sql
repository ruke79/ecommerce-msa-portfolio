-- 로그인 기기 이력 — 새 기기 로그인 감지(docs/44 #6, SECURITY_ALERT).
--
-- ROLLBACK-SAFE: 새 테이블 하나. 기존 데이터를 건드리지 않는다.
--
-- ── 왜 이게 먼저 필요했나 ────────────────────────────────────────────────
--
-- NotificationType.SECURITY_ALERT 는 메일 제목·SMS 문구·수신 설정 예외("사용자가 꺼도
-- 보낸다")까지 전부 갖춰져 있었다. 없는 것은 **그 알림을 만들어 내는 쪽** 하나였고,
-- 그러려면 "이 로그인이 처음 보는 기기인가"를 답할 수 있어야 한다. 비교할 이력이
-- 없으면 새 기기인지 알 수 없다.
--
-- ── 기기를 무엇으로 식별하는가 ──────────────────────────────────────────
--
-- 브라우저에 httpOnly 쿠키로 심는 **난수** 하나다. User-Agent 나 IP 로 지문을 만드는
-- 방식은 쓰지 않았다:
--   · IP 는 모바일에서 수시로 바뀐다 — 지하철에서 로그인할 때마다 "새 기기" 가 된다
--   · User-Agent 는 브라우저가 업데이트될 때마다 바뀐다
-- 둘 중 하나라도 지문에 넣으면 알림이 소음이 되고, 소음이 되면 사용자는 진짜 경고도
-- 무시한다.
--
-- 쿠키를 지우면 새 기기로 잡힌다. 그건 오탐이 아니다 — 쿠키를 지운 브라우저는 서버
-- 입장에서 처음 보는 브라우저와 구별되지 않는다.
--
-- ── 🔒 왜 토큰을 해시로 저장하는가 ──────────────────────────────────────
--
-- 이 값은 인증 수단이 아니다. 알고 있어도 로그인은 못 한다. 하지만 **보안 알림을 끌 수
-- 있는 값**이다 — 비밀번호를 이미 아는 공격자가 이 값까지 알면 알림 없이 조용히 들어온다.
-- DB 가 새더라도 그 능력이 함께 새지 않도록 해시만 저장한다(가입 확인 토큰과 같은 규칙).

CREATE TABLE IF NOT EXISTS users.known_device (
    device_id     bigint       GENERATED BY DEFAULT AS IDENTITY,
    user_id       bigint       NOT NULL,
    -- 쿠키에 담긴 난수의 SHA-256(hex). 원문은 어디에도 저장하지 않는다.
    token_hash    varchar(64)  NOT NULL,
    -- "Chrome · Windows" 같은 표시용 문자열. User-Agent 원문을 그대로 두지 않는다 —
    -- 지문 가치가 있는 값이고, 사용자에게 필요한 것은 "어느 브라우저였나" 뿐이다.
    label         varchar(120),
    -- 마스킹된 IP("203.0.113.xxx"). **표시 전용**이고 어떤 판정에도 쓰지 않는다.
    -- X-Forwarded-For 는 클라이언트가 위조할 수 있다(게이트웨이의 CustomUserKeyResolver
    -- 가 같은 이유로 이 헤더를 무시한다). 알림 문구를 조금 더 친절하게 만들 뿐이다.
    last_ip       varchar(64),
    first_seen_at timestamp(6) NOT NULL,
    last_seen_at  timestamp(6) NOT NULL,
    PRIMARY KEY (device_id),
    -- 같은 사람이 같은 기기를 두 번 가질 수 없다. 이게 없으면 동시 로그인 두 건이
    -- 각각 행을 만들고, 둘 다 "새 기기" 알림을 보낸다.
    CONSTRAINT uk_known_device UNIQUE (user_id, token_hash)
);

-- 로그인마다 "이 사람의 이 기기" 를 찾는다. 그리고 기기 수 상한을 지킬 때
-- 오래된 것부터 지우려면 last_seen_at 순서가 필요하다.
CREATE INDEX IF NOT EXISTS idx_known_device_user
    ON users.known_device (user_id, last_seen_at DESC);

-- FK 를 걸지 않는 이유는 이 저장소의 다른 곳과 같다: 탈퇴 처리가 사용자 행을 익명화만
-- 하고 지우지는 않으므로(WithdrawalService) 고아 행이 생길 경로가 사실상 없고, 설령
-- 생겨도 조회 조건(user_id)에 걸리지 않아 아무 영향이 없다.
