package com.project.notification_service.sms;

/**
 * SMS 발송 경로. 공급자를 갈아끼울 수 있게 인터페이스로 둔다.
 *
 * <p><b>왜 추상화하나.</b> 한국과 일본은 SMS 규제·요금·사업자가 서로 다르고, 한 공급자가 두
 * 나라를 다 잘 커버하지 않는 경우가 흔하다. 게다가 한국은 <b>발신번호 사전등록</b>이 법으로
 * 요구되어(전기통신사업법) 공급자 전환이 실제로 일어난다. 발송 코드가 특정 SDK 에 묶여 있으면
 * 그때 도메인 로직까지 뜯어야 한다.
 *
 * <p><b>"무료"에 대해.</b> 이 인터페이스 뒤의 라이브러리(libphonenumber 등)는 무료지만
 * <b>발송 자체는 어느 나라에서도 무료가 아니다</b> — 통신사가 건당 과금한다. 무료로 쓸 수 있는
 * 것은 개발용 {@link LoggingSmsSender} 와 공급자들이 주는 체험 크레딧뿐이다. 그래서 기본값을
 * 로깅 발송기로 두고, 실제 발송은 명시적으로 켜게 했다 — 설정을 잘못해 요금이 나가는 것보다
 * 아무것도 안 나가는 편이 낫다.
 */
public interface SmsSender {

    /**
     * @param e164    E.164 형식 수신번호 (PhoneNumbers.toE164 가 보장한다)
     * @param message 본문. 길이 제한은 구현체가 알아서 자른다 — §SmsMessage 참조
     * @return 발송 결과. 예외를 던지지 않고 결과로 돌려주는 이유는, 알림 하나가 실패했다고
     *         나머지 알림 처리까지 멈출 이유가 없기 때문이다
     */
    SmsResult send(String e164, String message);

    /** 이 발송기가 실제로 요금이 발생하는 경로인지. 관리·표시용. */
    boolean isLive();

    /** 설정에서 고를 때 쓰는 이름. */
    String name();
}
