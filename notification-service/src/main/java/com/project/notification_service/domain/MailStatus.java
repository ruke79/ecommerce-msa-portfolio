package com.project.notification_service.domain;

/**
 * 메일 1건의 발송 상태.
 *
 * <p>{@link SmsStatus} 와 같은 모양이지만 {@code NOT_APPLICABLE} 이 없다. SMS 는 알림 행에
 * 딸린 값이라 "이 알림은 문자 대상이 아니다"를 표현할 자리가 필요했지만, 메일은 <b>보낼 것으로
 * 판단된 뒤에야 행이 만들어지므로</b> 그런 상태가 존재하지 않는다.
 *
 * <p>일시적 실패와 영구적 실패를 나누는 이유는 SMS 와 같다. 메일에서는 SMTP 응답 코드가 그 구분을
 * 직접 알려 준다 — 4xx 는 일시(사서함 가득 참, 속도 제한), 5xx 는 영구(존재하지 않는 주소).
 * 이걸 뭉개면 잘못된 주소로 영원히 재시도하다 <b>발신 도메인이 스팸으로 분류된다.</b>
 */
public enum MailStatus {

    /** 보내야 하는데 아직 안 보냈다. */
    PENDING,

    /** MTA 가 접수했다. 수신함 도달은 별개다 — 바운스는 비동기로 돌아온다. */
    SENT,

    /** 일시적 실패. 다음 주기에 다시 집는다. */
    RETRYABLE,

    /** 영구 실패(주소 없음, 도메인 없음) 또는 재시도 상한 초과. 사람이 봐야 한다. */
    FAILED
}
