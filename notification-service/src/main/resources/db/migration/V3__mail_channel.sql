-- 메일 채널 — SMS 옆에 EMAIL 을 붙인다 (docs/29).
--
-- 왜 notification 테이블에 컬럼을 더하지 않고 새 테이블을 만드나:
--   가입 확인·비밀번호 재설정 메일은 인앱 알림이 아니다. 받는 사람이 아직 로그인조차 하지
--   않았고, 알림 목록에 보여줄 것도 아니다. 게다가 notification.recipient_id 는 NOT NULL 이라
--   사용자 id 를 모르는 메일은 저장조차 못 한다. 그래서 메일은 자기 아웃박스를 갖는다.
--
-- 모든 문장이 멱등이다(V2 와 같은 규칙).

-- ── 메일 아웃박스 ────────────────────────────────────────────────────────
--
-- params 에 대하여: 가입 확인 링크·비밀번호 재설정 링크가 여기 들어간다. 그 자체로 계정을
-- 활성화하거나 비밀번호를 바꿀 수 있는 자격증명이므로,
--   · 발송이 끝나는 즉시 애플리케이션이 NULL 로 지우고 (MailMessage#recordAttempt)
--   · 끝내 발송되지 못한 행은 24시간 뒤 정리 작업이 지운다 (MailDispatcher#scrubStaleParams)
-- 행 자체는 남긴다 — "왜 메일이 안 갔나"는 나중에도 볼 수 있어야 한다.

CREATE TABLE IF NOT EXISTS notification.mail_message (
    mail_id           bigint generated by default as identity,
    to_email          varchar(320) not null,
    recipient_user_id bigint,
    kind              varchar(40) not null check (kind in (
                          'REGISTRATION_CONFIRM','PASSWORD_RESET','ORDER_PLACED',
                          'PAYMENT_COMPLETED','PAYMENT_FAILED','SHIPPING_UPDATED',
                          'COUPON_ISSUED','SECURITY_ALERT')),
    params            varchar(2000),
    locale            varchar(10),
    status            varchar(20) not null check (status in ('PENDING','SENT','RETRYABLE','FAILED')),
    attempts          integer not null,
    detail            varchar(300),
    source_event_id   varchar(120) unique,
    created_at        timestamp(6) not null,
    completed_at      timestamp(6),
    primary key (mail_id)
);

-- 디스패처가 매 주기 도는 질의를 받친다. 이게 없으면 보낸 메일이 쌓일수록 폴링이 전체 스캔이 된다.
CREATE INDEX IF NOT EXISTS idx_mail_message_status
    ON notification.mail_message (status, created_at);

-- 운영 조회: "이 사람에게 나간 메일". 문의 대응에 매번 필요하다.
CREATE INDEX IF NOT EXISTS idx_mail_message_recipient
    ON notification.mail_message (to_email, created_at);

-- ── 수신 설정에 메일 채널 추가 ──────────────────────────────────────────
--
-- email 은 게이트웨이가 JWT 에서 꺼내 붙이는 User-Email 헤더에서 채워진다. 사용자가 입력하는
-- 값이 아니라 로그인 계정 주소이므로 번호처럼 따로 인증하지 않는다(NotificationPreference 주석).
--
-- 길이 320 은 RFC 5321 §4.5.3.1.3 의 경로 상한이다. 더 짧으면 유효한 주소가 잘려 저장되고,
-- 그러면 메일이 엉뚱한 곳으로 간다.

ALTER TABLE notification.notification_preference
    ADD COLUMN IF NOT EXISTS email varchar(320);

-- DEFAULT 를 함께 준다. 기존 행이 있는 테이블에 기본값 없는 NOT NULL 은 붙지 않기 때문이다.
-- PostgreSQL 11+ 는 이 형태를 테이블 재작성 없이 처리한다(카탈로그에만 기록).
ALTER TABLE notification.notification_preference
    ADD COLUMN IF NOT EXISTS email_enabled boolean not null default true;
