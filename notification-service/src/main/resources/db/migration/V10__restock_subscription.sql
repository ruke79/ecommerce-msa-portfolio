-- 재입고 알림 (docs/53).
--
-- ROLLBACK-SAFE: 새 테이블 하나를 만들고, 두 CHECK 에 RESTOCK_AVAILABLE 을 더한다(허용 범위를 넓히기만).
--
-- 품절된 옵션(상품·색상·사이즈)에 "재입고되면 알려 주세요" 를 신청한 기록이다. catalog-service 가 그 옵션의
-- 재고가 0 에서 다시 생겼다고 알리면(product-stock, RESTOCKED) 아직 알리지 않은 신청마다 알림을 만들고
-- notified_at 을 찍는다. 다시 신청하면 알린 행을 지우고 새로 만든다 — 알림 키가 신청 id 라 새 id 여야
-- 다음 재입고도 알린다.

CREATE TABLE IF NOT EXISTS notification.restock_subscription (
    subscription_id bigint generated by default as identity,
    user_id         bigint not null,
    product_id      bigint not null,
    -- 색상 없는 상품은 0. null 을 두면 UNIQUE 가 같은 신청 둘을 막지 못한다(null 은 서로 다르다).
    color_id        bigint not null default 0,
    size            varchar(64) not null,
    product_name    varchar(255),
    product_slug    varchar(255),
    created_at      timestamp(6) not null,
    notified_at     timestamp(6),
    primary key (subscription_id),
    constraint uq_restock_subscription unique (user_id, product_id, color_id, size)
);

-- 재입고가 오면 "이 옵션의 아직 안 알린 신청" 을 읽는다.
CREATE INDEX IF NOT EXISTS idx_restock_pending
    ON notification.restock_subscription (product_id, color_id, size)
    WHERE notified_at IS NULL;

-- 알림 종류 RESTOCK_AVAILABLE — V9 와 같은 방식으로 두 CHECK 를 다시 건다(B-55).

DO $$
DECLARE
    c record;
BEGIN
    FOR c IN
        SELECT con.conname
          FROM pg_constraint con
          JOIN pg_attribute att
            ON att.attrelid = con.conrelid
           AND att.attnum = ANY (con.conkey)
         WHERE con.conrelid = 'notification.notification'::regclass
           AND con.contype = 'c'
           AND att.attname = 'type'
    LOOP
        EXECUTE format('ALTER TABLE notification.notification DROP CONSTRAINT %I', c.conname);
    END LOOP;
END $$;

ALTER TABLE notification.notification
    ADD CONSTRAINT notification_type_check
    CHECK (type IN ('ORDER_PLACED', 'PAYMENT_COMPLETED', 'PAYMENT_FAILED', 'PAYMENT_REFUNDED',
                    'SHIPPING_UPDATED', 'ORDER_COMPLETED', 'CHAT_MESSAGE', 'FRIEND_ONLINE',
                    'COUPON_ISSUED', 'SECURITY_ALERT', 'NOTICE_PUBLISHED', 'ANNOUNCEMENT',
                    'EVENT_STARTED', 'RESTOCK_AVAILABLE'));

DO $$
DECLARE
    c record;
BEGIN
    FOR c IN
        SELECT con.conname
          FROM pg_constraint con
          JOIN pg_attribute att
            ON att.attrelid = con.conrelid
           AND att.attnum = ANY (con.conkey)
         WHERE con.conrelid = 'notification.mail_message'::regclass
           AND con.contype = 'c'
           AND att.attname = 'kind'
    LOOP
        EXECUTE format('ALTER TABLE notification.mail_message DROP CONSTRAINT %I', c.conname);
    END LOOP;
END $$;

ALTER TABLE notification.mail_message
    ADD CONSTRAINT mail_message_kind_check
    CHECK (kind IN ('REGISTRATION_CONFIRM', 'PASSWORD_RESET', 'ORDER_PLACED',
                    'PAYMENT_COMPLETED', 'PAYMENT_FAILED', 'PAYMENT_REFUNDED', 'SHIPPING_UPDATED',
                    'ORDER_COMPLETED', 'COUPON_ISSUED', 'SECURITY_ALERT', 'RESTOCK_AVAILABLE'));
