-- notification-service 스키마 베이스라인 — Flyway 가 스키마를 소유한다 (docs/20).
--
-- ⚠️ 손으로 쓰지 말 것. Hibernate 가 엔티티에서 생성한 DDL 을 기계 변환한 것이다:
--     ./gradlew -PexportSchema -PwithContainers :notification-service:test --tests '*ApplicationTests*'
--     ./ops/tools/hbm2flyway.py build/schema/notification-service.sql -o <이 파일>
--
-- 왜 베이스라인이 필요한가: 예전에는 `ddl-auto: update` 가 스키마를 만들었다. 그래서
--   · 스키마 변경이 이력에 남지 않고 (무엇이 언제 왜 바뀌었는지 아무도 모른다)
--   · 운영 DB 에 예고 없는 DDL 이 나가며
--   · 제약을 **지우지는 않아** 잘못된 제약이 영원히 남는다 (V4 가 그 뒤처리였다)
-- 이제 Flyway 가 소유하고 Hibernate 는 `validate` 로 검증만 한다.
--
-- 모든 문장이 멱등이다. 빈 DB 에서는 전부 만들고, `ddl-auto` 가 이미 만들어 둔 DB 에서는
-- 전부 건너뛴다. 그래서 기존 환경도 이 마이그레이션을 그대로 통과한다.
--
-- 파일 끝의 `add column if not exists` 묶음은 기존 DB 가 엔티티보다 **뒤처진** 경우를 메운다.
-- "그건 ddl-auto 랑 뭐가 다르냐"에 대한 답: ddl-auto 는 매 기동마다 그때의 코드에서 DDL 을
-- 새로 유추해 **검토 없이** 실행한다. 이건 커밋된 파일에 적힌 고정된 문장 목록이고, 리뷰를
-- 거치며, Flyway 가 기록하므로 **딱 한 번만** 실행된다. 뒤에 스키마를 또 바꾸려면 새 마이그
-- 레이션을 써야 한다. 컬럼은 반드시 널 허용으로 추가한다 — 기존 행이 있는 테이블에 기본값
-- 없는 NOT NULL 은 붙지 않기 때문이고, validate 는 널 여부가 아니라 존재와 타입만 본다.
--
-- 스키마 1 · 시퀀스 0 · 테이블 3 · 인덱스 4 · 제약 0

CREATE SCHEMA IF NOT EXISTS notification;

CREATE TABLE IF NOT EXISTS notification.notification (
    deleted boolean not null,
    read_status boolean not null,
    sms_attempts integer not null,
    created_at timestamp(6) not null,
    notification_id bigint generated by default as identity,
    recipient_id bigint not null,
    sms_status varchar(20) not null check (sms_status in ('NOT_APPLICABLE','PENDING','SENT','RETRYABLE','FAILED')),
    type varchar(40) not null check (type in ('ORDER_PLACED','PAYMENT_COMPLETED','PAYMENT_FAILED','SHIPPING_UPDATED','CHAT_MESSAGE','FRIEND_ONLINE','COUPON_ISSUED','SECURITY_ALERT')),
    source_event_id varchar(120) unique,
    title varchar(120) not null,
    sms_detail varchar(300),
    url varchar(300),
    content varchar(500) not null,
    primary key (notification_id)
);

CREATE TABLE IF NOT EXISTS notification.notification_preference (
    phone_verified boolean not null,
    region varchar(2),
    sms_enabled boolean not null,
    two_factor_enabled boolean not null,
    preference_id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    user_id bigint not null unique,
    phone_e164 varchar(20),
    primary key (preference_id)
);

CREATE TABLE IF NOT EXISTS notification.phone_verification (
    attempts integer not null,
    consumed boolean not null,
    created_at timestamp(6) not null,
    expires_at timestamp(6) not null,
    user_id bigint,
    verification_id bigint generated by default as identity,
    phone_e164 varchar(20) not null,
    code_hash varchar(100) not null,
    primary key (verification_id)
);

CREATE INDEX IF NOT EXISTS idx_notification_recipient on notification.notification (recipient_id, created_at);

CREATE INDEX IF NOT EXISTS idx_notification_unread on notification.notification (recipient_id, read_status);

CREATE INDEX IF NOT EXISTS idx_notification_sms_status on notification.notification (sms_status, created_at);

CREATE INDEX IF NOT EXISTS idx_phone_verification_lookup on notification.phone_verification (phone_e164, consumed, expires_at);

