CREATE SCHEMA IF NOT EXISTS chat;

CREATE TABLE IF NOT EXISTS chat.member (
    member_id bigint not null,
    email varchar(255),
    image_url varchar(255),
    nickname varchar(255),
    role varchar(255) check (role in ('GUEST','USER')),
    primary key (member_id),
    constraint uk_member_email unique (email),
    constraint uk_member_nickname unique (nickname)
);

CREATE INDEX IF NOT EXISTS idx_member_email on chat.member (email);

CREATE INDEX IF NOT EXISTS idx_member_nickname on chat.member (nickname);

CREATE TABLE IF NOT EXISTS alarm (
    delete_status boolean,
    read_status boolean,
    alarm_id bigint generated by default as identity,
    mod_date timestamp(6),
    receiver_id bigint,
    reg_date timestamp(6),
    sender_id bigint,
    version bigint,
    content varchar(255),
    sender_name varchar(255),
    type varchar(255) check (type in ('CHAT')),
    url varchar(255),
    primary key (alarm_id)
);

CREATE TABLE IF NOT EXISTS chat_room (
    room_id bigint generated by default as identity,
    room_name varchar(255) not null,
    room_uid varchar(255) not null,
    primary key (room_id)
);

CREATE TABLE IF NOT EXISTS participant_chat_room (
    member_id bigint,
    participant_id bigint generated by default as identity,
    room_id bigint,
    primary key (participant_id)
);

