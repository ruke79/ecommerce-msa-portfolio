-- delivery-service 스키마 베이스라인 — Flyway 가 스키마를 소유한다 (docs/20).
--
-- ⚠️ 손으로 쓰지 말 것. Hibernate 가 엔티티에서 생성한 DDL 을 기계 변환한 것이다:
--     ./gradlew -PexportSchema -PwithContainers :delivery-service:test --tests '*ApplicationTests*'
--     ./ops/tools/hbm2flyway.py build/schema/delivery-service.sql -o <이 파일>
--
-- 왜 베이스라인이 필요한가: 예전에는 `ddl-auto: update` 가 스키마를 만들었다. 그래서
--   · 스키마 변경이 이력에 남지 않고 (무엇이 언제 왜 바뀌었는지 아무도 모른다)
--   · 운영 DB 에 예고 없는 DDL 이 나가며
--   · 제약을 **지우지는 않아** 잘못된 제약이 영원히 남는다 (V4 가 그 뒤처리였다)
-- 이제 Flyway 가 소유하고 Hibernate 는 `validate` 로 검증만 한다.
--
-- 모든 문장이 멱등이다. 빈 DB 에서는 전부 만들고, `ddl-auto` 가 이미 만들어 둔 DB 에서는
-- 전부 건너뛴다. 그래서 기존 환경도 이 마이그레이션을 그대로 통과한다.
--
-- 파일 끝의 `add column if not exists` 묶음은 기존 DB 가 엔티티보다 **뒤처진** 경우를 메운다.
-- "그건 ddl-auto 랑 뭐가 다르냐"에 대한 답: ddl-auto 는 매 기동마다 그때의 코드에서 DDL 을
-- 새로 유추해 **검토 없이** 실행한다. 이건 커밋된 파일에 적힌 고정된 문장 목록이고, 리뷰를
-- 거치며, Flyway 가 기록하므로 **딱 한 번만** 실행된다. 뒤에 스키마를 또 바꾸려면 새 마이그
-- 레이션을 써야 한다. 컬럼은 반드시 널 허용으로 추가한다 — 기존 행이 있는 테이블에 기본값
-- 없는 NOT NULL 은 붙지 않기 때문이고, validate 는 널 여부가 아니라 존재와 타입만 본다.
--
-- 스키마 1 · 시퀀스 0 · 테이블 6 · 인덱스 7 · 제약 4

CREATE SCHEMA IF NOT EXISTS delivery;

CREATE TABLE IF NOT EXISTS delivery.address_change (
    address_change_id bigint generated by default as identity,
    changed_at timestamp(6) not null,
    changed_by bigint not null,
    delivery_id bigint not null,
    reason varchar(200),
    new_address varchar(600) not null,
    previous_address varchar(600) not null,
    primary key (address_change_id)
);

CREATE TABLE IF NOT EXISTS delivery.carrier (
    active boolean not null,
    supports_tracking boolean not null,
    carrier_code varchar(30) not null,
    name_en varchar(60),
    name_ko varchar(60) not null,
    tracking_url varchar(300),
    primary key (carrier_code)
);

CREATE TABLE IF NOT EXISTS delivery.delivery (
    country varchar(2) not null,
    created_at timestamp(6) not null,
    customer_id bigint not null,
    delivery_id bigint generated by default as identity,
    order_id bigint not null unique,
    reordered_from_order_id bigint,
    updated_at timestamp(6) not null,
    version bigint,
    postal_code varchar(12),
    recipient_phone varchar(20),
    city varchar(80),
    recipient_name varchar(80) not null,
    state varchar(80),
    address_line1 varchar(200) not null,
    address_line2 varchar(200),
    delivery_memo varchar(200),
    primary key (delivery_id)
);

CREATE TABLE IF NOT EXISTS delivery.delivery_event (
    created_at timestamp(6) not null,
    event_id bigint generated by default as identity,
    occurred_at timestamp(6) not null,
    shipment_id bigint not null,
    status varchar(24) not null check (status in ('PENDING','INFO_RECEIVED','PICKED_UP','IN_TRANSIT','CUSTOMS_HOLD','CUSTOMS_CLEARED','OUT_FOR_DELIVERY','ATTEMPT_FAILED','DELIVERED','EXCEPTION','RETURNED','CANCELLED')),
    dedup_key varchar(120) not null,
    location varchar(120),
    raw_status varchar(120),
    description varchar(300),
    raw_payload jsonb,
    primary key (event_id)
);

CREATE TABLE IF NOT EXISTS delivery.shipment (
    international boolean not null,
    poll_failures integer not null,
    sequence_no integer not null,
    created_at timestamp(6) not null,
    delivered_at timestamp(6),
    delivery_id bigint not null,
    dispatched_at timestamp(6),
    estimated_at timestamp(6),
    last_synced_at timestamp(6),
    next_poll_at timestamp(6),
    shipment_id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    version bigint,
    status varchar(24) not null check (status in ('PENDING','INFO_RECEIVED','PICKED_UP','IN_TRANSIT','CUSTOMS_HOLD','CUSTOMS_CLEARED','OUT_FOR_DELIVERY','ATTEMPT_FAILED','DELIVERED','EXCEPTION','RETURNED','CANCELLED')),
    carrier_code varchar(30),
    customs_clearance_no varchar(40),
    customs_declaration_no varchar(40),
    tracking_number varchar(60),
    primary key (shipment_id),
    constraint uk_shipment_tracking unique (carrier_code, tracking_number)
);

CREATE TABLE IF NOT EXISTS delivery.shipment_item (
    quantity integer not null,
    order_product_id bigint,
    product_id bigint,
    shipment_id bigint not null,
    shipment_item_id bigint generated by default as identity,
    product_name varchar(300),
    image_url varchar(500),
    primary key (shipment_item_id)
);

CREATE INDEX IF NOT EXISTS idx_address_change_delivery on delivery.address_change (delivery_id, changed_at);

CREATE INDEX IF NOT EXISTS idx_delivery_customer on delivery.delivery (customer_id, created_at);

CREATE INDEX IF NOT EXISTS idx_delivery_order on delivery.delivery (order_id);

CREATE INDEX IF NOT EXISTS idx_delivery_event_timeline on delivery.delivery_event (shipment_id, occurred_at);

CREATE INDEX IF NOT EXISTS idx_shipment_poll on delivery.shipment (next_poll_at);

CREATE INDEX IF NOT EXISTS idx_shipment_delivery on delivery.shipment (delivery_id);

CREATE INDEX IF NOT EXISTS idx_shipment_item_shipment on delivery.shipment_item (shipment_id);

